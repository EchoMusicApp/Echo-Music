"""Generates desktop stand-ins for Android's R.string / R.plurals and stringResource() from the
original app's res/values/strings.xml. Run from the repo root: python3 desktop/orig-core/tools/gen_r.py"""
import re, xml.etree.ElementTree as ET

SRC = "app/src/main/res/values/strings.xml"
OUT = "desktop/orig-core/src/main/kotlin"

def unescape(s: str) -> str:
    s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] == '"':
        s = s[1:-1]
    return (s.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n").replace("\\@", "@").replace("\\?", "?")
             .replace("\\\\", "\\"))

def text(el) -> str:
    return unescape("".join(el.itertext()))

root = ET.parse(SRC).getroot()
strings = [(e.get("name"), text(e)) for e in root.findall("string") if e.get("translatable") != "false"]
plurals = []
for p in root.findall("plurals"):
    plurals.append((p.get("name"), {i.get("quantity"): text(i) for i in p.findall("item")}))

def ident(n): return re.sub(r"\W", "_", n)
def lit(s):  return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'

ids = []
k = 0
with open(f"{OUT}/echo/music/iad1tya/R.kt", "w") as f:
    f.write("// GENERATED by desktop/orig-core/tools/gen_r.py from res/values/strings.xml. Do not edit.\n")
    f.write("package echo.music.iad1tya\n\n/** Desktop stand-in for Android's generated R (strings and plurals only for now). */\nobject R {\n")
    f.write("    object string {\n")
    for n, _ in strings:
        k += 1; ids.append(("s", n, k)); f.write(f"        const val {ident(n)} = {k}\n")
    f.write("    }\n    object plurals {\n")
    for n, _ in plurals:
        k += 1; ids.append(("p", n, k)); f.write(f"        const val {ident(n)} = {k}\n")
    f.write("    }\n}\n")

with open(f"{OUT}/echo/music/iad1tya/RTable.kt", "w") as f:
    f.write("// GENERATED by desktop/orig-core/tools/gen_r.py. Do not edit.\npackage echo.music.iad1tya\n\n")
    f.write("object RTable {\n    val strings: Map<Int, String> = mapOf(\n")
    for (n, t), (_, _, i) in zip(strings, [x for x in ids if x[0] == "s"]):
        f.write(f"        {i} to {lit(t)},\n")
    f.write("    )\n    val plurals: Map<Int, Map<String, String>> = mapOf(\n")
    for (n, q), (_, _, i) in zip(plurals, [x for x in ids if x[0] == "p"]):
        f.write(f"        {i} to mapOf(" + ", ".join(f"{lit(a)} to {lit(b)}" for a, b in q.items()) + "),\n")
    f.write("    )\n}\n")
print(len(strings), "strings,", len(plurals), "plurals")
